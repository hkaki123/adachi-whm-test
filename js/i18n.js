/* 言語の決定と文字列取得 */
window.WHM_I18N = (function () {
  const langs = window.WHM_CONFIG.languages;
  function detect() {
    const q = new URLSearchParams(location.search).get("lang");
    if (q && langs.includes(q)) return q;
    try {
      const s = localStorage.getItem("whm_lang");
      if (s && langs.includes(s)) return s;
    } catch (e) { /* storage unavailable */ }
    const nav = (navigator.language || "ja").toLowerCase();
    if (nav.startsWith("ja")) return "ja";
    if (nav.startsWith("zh")) return /tw|hk|hant/.test(nav) ? "zh-Hant" : "zh-Hans";
    if (nav.startsWith("pt")) return "pt";
    if (nav.startsWith("en")) return "en";
    return "ja";
  }
  let lang = detect();
  function t(key, vars) {
    let s = (I18N[lang] && I18N[lang][key]) ?? I18N.ja[key] ?? key;
    if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
    return s;
  }
  function setLang(l) {
    lang = l;
    try { localStorage.setItem("whm_lang", l); } catch (e) { /* ignore */ }
    document.documentElement.lang = I18N[l].htmlLang;
  }
  function applyStatic(root) {
    (root || document).querySelectorAll("[data-i18n]").forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
    (root || document).querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    (root || document).querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  }
  function buildSelect(sel, onChange) {
    sel.innerHTML = langs.map((l) => `<option value="${l}">${I18N[l].langName}</option>`).join("");
    sel.value = lang;
    sel.addEventListener("change", () => onChange(sel.value));
  }
  document.documentElement.lang = I18N[lang].htmlLang;
  return { t, setLang, applyStatic, buildSelect, get lang() { return lang; } };
})();
